/** Source labels here are generated UI metadata, never authored node/font text. */
export function stylePropertyLabel(field: 'fills' | 'strokes' | 'effects', index: number, suffix: string, locale: InterfaceLocale) {
  const titles = { fills: '填充', strokes: '描边', effects: '效果' }
  if (locale !== 'en') return `${titles[field]} ${index + 1}${suffix}`
  const details: Record<string, string> = {
    '颜色': 'color', '不透明度 %': 'opacity %', '混合模式': 'blend mode', '渐变角度': 'gradient angle',
    '图片适配': 'image fit', '粗细': 'width', '位置': 'position', '端点': 'cap', '连接': 'join',
    '模糊': 'blur', '阴影颜色': 'shadow color', '偏移 X': 'offset X', '偏移 Y': 'offset Y', '扩展': 'spread',
    '强度 %': 'intensity %', '幅度': 'amount', '深度': 'depth', '倒角宽度': 'bevel width',
    '磨砂': 'frost', '折射 %': 'refraction %', '色散 %': 'dispersion %', '光线角度': 'light angle', '照明 %': 'light intensity',
    '纹理宽': 'texture width', '纹理高': 'texture height',
  }
  const stop = /^色标 (\d+)$/.exec(suffix), offset = /^色标位置 (\d+) %$/.exec(suffix)
  const detail = stop ? `color stop ${stop[1]}` : offset ? `color stop ${offset[1]} position %` : details[suffix] ?? translateProperty(suffix, locale)
  return `${translateProperty(titles[field], locale)} ${index + 1}${detail ? ` ${detail}` : ''}`
}

export type PropertyStatus = string | { zh: string; en: string }
export function propertyStatusText(status: PropertyStatus, locale: InterfaceLocale): string {
  if (typeof status !== 'string') return locale === 'en' ? status.en : status.zh
  // Errors are display text only. Unknown backend diagnostics remain verbatim.
  if (status.startsWith('Error: ')) return `Error: ${propertyStatusText(status.slice(7), locale)}`
  const facePrefix = '字体文件没有唯一匹配的字形：'
  if (locale === 'en' && status.startsWith(facePrefix)) return `The font file has no unique matching face: ${status.slice(facePrefix.length)}`
  return translateProperty(status, locale)
}
export function fontEditStatus(result: import('./font-management').FontEditResult, operation: 'apply' | 'replace'): PropertyStatus {
  if (result.status === 'blocked' || result.status === 'rejected' || result.message === '原字体与目标字体相同') return result.message
  const en = operation === 'apply' ? `Applied to ${result.changedNodes} text layers`
    : `Replaced ${result.changedReferences} references in ${result.changedNodes} text layers${result.skippedLocked || result.skippedLinked ? `; skipped ${result.skippedLocked} locked and ${result.skippedLinked} shared-style layers` : ''}`
  return { zh: result.message, en }
}
